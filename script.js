async function buscarPokemon(nome){
    try {
        const resposta = await fetch(
            `https://pokeapi.co/api/v2/pokemon/${nome}`
        );

        if (!resposta.ok){
            throw new Error("Pokémon não encontrado");
        }

        const pokemon = await resposta.json();

        numeroAtual = pokemon.id;
        pokemonAtual = pokemon;
        modoShiny = false;
        botaoShiny.innerText = "☆";

        nomePokemon.innerText = pokemon.name;
        numeroPokemon.innerText = `Nº ${pokemon.id}`;
        tiposPokemon.innerHTML = pokemon.types
            .map(tipo => {
                const nome = tipo.type.name;
                const traducao = traducaoTipos[nome];

                return `<span class="tipo tipo-${nome}">${traducao}</span>`;
            })
            .join("");

        document.getElementById("altura-pokemon").innerText =
            (pokemon.height / 10) + " m";

        document.getElementById("peso-pokemon").innerText =
            (pokemon.weight / 10) + " kg";

        imagemPokemon.src = pokemon.sprites.front_default;

        const idsAtributos ={
            "hp": "vida",
            "attack": "ataque",
            "defense": "defesa",
            "special-attack": "ataque-sp",
            "special-defense": "defesa-sp",
            "speed": "velocidade"
        };

        pokemon.stats.forEach(atributo =>{
            const nome = atributo.stat.name;
            const valor = atributo.base_stat;
            const elemento = document.getElementById(idsAtributos[nome]);
            const barra = document.getElementById(idsAtributos[nome] + "-barra");

            elemento.innerText = valor;

            barra.style.width = Math.min((valor / 255) * 100, 100) + "%";
            barra.style.backgroundColor = corDoAtributo(valor);
        });

    } catch (erro){
        alert("Pokémon não encontrado. Verifique o nome ou número.");
    }
}


function corDoAtributo(valor) {
    if (valor < 50) {
        return "#e74c3c";
    }

    if (valor < 90) {
        return "#f1c40f";
    }

    return "#42b642";
}


function alternarShiny(){
    if (pokemonAtual === null){
        return;
    }

    modoShiny = !modoShiny;

    if (modoShiny && pokemonAtual.sprites.front_shiny){
        imagemPokemon.src = pokemonAtual.sprites.front_shiny;
        botaoShiny.innerText = "★";
    } else{
        modoShiny = false;
        imagemPokemon.src = pokemonAtual.sprites.front_default;
        botaoShiny.innerText = "☆";
    }
}

function pokemonAnterior() {
    if (numeroAtual > 1) {
        buscarPokemon(numeroAtual - 1);
    }
}

function pokemonProximo() {
    buscarPokemon(numeroAtual + 1);
}

function pokemonAleatorio() {
    const numero = Math.floor(Math.random() * 1025) + 1;

    buscarPokemon(numero);
}

formulario.addEventListener("submit", function (event){
    event.preventDefault();

    const nome = campoBusca.value.trim().toLowerCase();

    if (nome === ""){
        alert("Digite o nome ou número de um Pokémon!");
        return;
    }

    buscarPokemon(nome);
});

botaoShiny.addEventListener("click", alternarShiny);

botaoAnterior.addEventListener("click", pokemonAnterior);
botaoProximo.addEventListener("click", pokemonProximo);

botaoAleatorio.addEventListener("click", pokemonAleatorio); 


